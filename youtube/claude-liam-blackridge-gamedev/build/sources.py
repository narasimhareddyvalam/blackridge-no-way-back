"""Writes the reel's SOURCES.md: source revision, every evidence file shown (with SHA-256),
how each was made, tools and licences. Run: python3 build/sources.py"""
import hashlib
import json
import subprocess
from pathlib import Path

REEL = Path(__file__).resolve().parents[1]
REPO = REEL.parents[1]


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


rev = (REEL / "build" / "revision.txt").read_text().strip()
toolkit = subprocess.run(["git", "-C", str(Path.home() / "Desktop/brutalist.art"), "rev-parse", "--short", "HEAD"],
                         capture_output=True, text=True).stdout.strip()
sheet = json.loads((REEL / "beat_sheet.json").read_text())
used = {}
for b in sheet["beats"]:
    props = b["shot"].get("remotion", {}).get("props", {})
    for m in props.get("media", []):
        rel = m["src"].removeprefix("blackridge-shaded/")
        used.setdefault(rel, []).append(b["beat_id"])
    if b["shot"].get("evidence_media"):
        used.setdefault(b["shot"]["evidence_media"], []).append(b["beat_id"] + " (paired evidence)")

lines = ["# SOURCES — Blackridge, Shaded", "",
         f"- Game source shown: {rev}. Nothing under `game/` was edited for the film; the engine captures ran on an "
         "isolated copy with its own user-data folder (`capture/CAPTURE.md`).",
         f"- Toolkit: Brutalist `brutalist.art` at `{toolkit}` plus this build's local additions "
         "(`GodotEngineEvidence`, GodotDevWorkbench `dense` and `//` comments — see BUILD-LOG.md).",
         "- Engine: Godot 4.7.2.stable (MIT), Compatibility renderer `gl_compatibility` (opengl3, Apple M4); one "
         "Forward+ comparison run (`--rendering-method forward_plus`, Metal) for the hint experiment only.", "",
         "## Evidence shown (hash at build time)", "", "| File | Beats | SHA-256 | Made by |", "| --- | --- | --- | --- |"]
for rel in sorted(used):
    p = REEL / rel
    how = ("scripted engine capture (`capture/scripts/`, `capture/CAPTURE.md`)" if rel.startswith("capture/") else
           "copy of the repository file of the same name" if not rel.startswith("evidence/recorded") and not rel.startswith("evidence/window")
           else "typeset by build/evidence.py from verbatim log/report lines")
    if rel.startswith("evidence/night_cluster"):
        how = "copy of `evidence/captures/` (scripted SubViewport capture, `tools/captures/capture_night_cluster.gd`)"
    if rel.startswith("evidence/fog_"):
        how = "copy of `game/assets/textures/windshield/` (generated by `tools/make_fog_textures.py`, seed 20261029)"
    if rel.endswith("_keyframes.png"):
        how = "four frames extracted with ffmpeg from the take of the same name (the MP4 itself stays out of Git)"
    lines.append(f"| `{rel}` | {', '.join(sorted(set(used[rel])))} | `{sha(p) if p.exists() else 'missing'}` | {how} |")
lines += ["", "MP4 clips are kept out of Git, per the course's media rule. Their hashes are in "
          "`capture/manifest.json` and above.", "",
          "## Generated or third-party material",
          "",
          "- **Textures:** fog_color, fog_normal and fog_data were written by code (`tools/make_fog_textures.py`, by "
          "Claude Code) and are original. `greys_3x1.png` was written by `tools/make_hint_png.gd`.",
          "- **Calibration only:** Poly Haven `box_profile_metal_sheet` nor_gl / nor_dx, CC0 1.0. They are used only by "
          "the curl test (`game/tests/calibration/ATTRIBUTION.md`).",
          "- **Narration:** Kokoro-82M (Apache-2.0) via kokoro-onnx (MIT), voice `am_onyx`, local and free; "
          "voiced as Liam, in for Bear. No voice cloning, no paid TTS.",
          "- **Word timing:** faster-whisper (MIT) with the Whisper `base` model, via the toolkit's `align.py`.",
          "- **Rendering:** Remotion 4.0.486 under the Remotion Free License (individual use); ffmpeg 8.0.1.",
          "- **Maths:** matplotlib 3.11 mathtext through the toolkit's `typeset_math.py`.",
          "- **Fonts:** EB Garamond, Lato, Inter and PT Mono (SIL Open Font License, bundled with the toolkit).",
          "- **No image, video or music generator was used.** No paid media.", "",
          "## Who did what",
          "",
          "- **Author:** the brief and the hand predictions; the three shaders; the generated-shader "
          "annotations; LANGUAGE-NOTES; the playtest; the decisions; script approval; the instruction "
          "that the narration never frames the work as course requirements.",
          "- **Claude Code:**",
          "  - the CLAUDE.md draft, driver, tests, texture script, materials and overlays, captures, "
          "audit and reports;",
          "  - this film's script draft, beat sheet, narration text, evidence ledger and new component;",
          "  - the capture drivers, through a subagent.",
          ""]
(REEL / "SOURCES.md").write_text("\n".join(lines) + "\n")
print(f"SOURCES.md: {len(used)} evidence files")
