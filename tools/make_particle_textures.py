"""Draw the five particle textures for Assignment 6's effects (CHANGE-BRIEF.md §6).

Each is a white sprite whose alpha carries the shape; the particle's own colour and alpha
curve tint and fade it, because the draw materials use vertex colour as albedo. The noise
uses a fixed seed, so every run writes byte-identical files. Nothing is sourced or
generated by an AI model; this script is the textures' provenance record.

- water_bead.png (64 x 64): a water bead, clear in the middle with a brighter rim and a
  small highlight, as a drop refracts and reflects light (A1 BigDrops, A2 RoofBeads, B1
  LampSplash).
- fine_spray.png (64 x 64): a soft round speck of mist (A1 FineSpray).
- roof_stream.png (64 x 64): a short tapered stream of water, upright (A2 RoofStreams).
- rain_streak.png (16 x 256): a thin raindrop streak, upright, fading at both ends, the
  motion-blurred look of a falling drop (B1 LampRain).
- exhaust_puff.png (128 x 128): a soft, uneven puff of condensed vapour (B2).

Usage, from the repository root:
    python3 -I tools/make_particle_textures.py
"""

import pathlib

import numpy as np
from PIL import Image

OUT = pathlib.Path("game/effects/textures")
SEED = 6


def grid(width: int, height: int) -> tuple[np.ndarray, np.ndarray]:
    """Pixel-centre coordinates from -1 to 1 across and down."""
    x = (np.arange(width) + 0.5) / width * 2.0 - 1.0
    y = (np.arange(height) + 0.5) / height * 2.0 - 1.0
    return np.meshgrid(x, y)


def smoothstep(edge0: float, edge1: float, value: np.ndarray) -> np.ndarray:
    t = np.clip((value - edge0) / (edge1 - edge0), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def save(name: str, alpha: np.ndarray, value: np.ndarray | None = None) -> None:
    """Write white (or `value`-shaded) RGB with the given alpha, both 0..1."""
    shade = np.ones_like(alpha) if value is None else value
    rgb = np.clip(shade, 0.0, 1.0)
    pixels = np.dstack([rgb, rgb, rgb, np.clip(alpha, 0.0, 1.0)])
    image = Image.fromarray(np.round(pixels * 255.0).astype(np.uint8), "RGBA")
    OUT.mkdir(parents=True, exist_ok=True)
    image.save(OUT / name, optimize=False)
    print(f"wrote {OUT / name} ({image.width} x {image.height})")


def water_bead() -> None:
    x, y = grid(64, 64)
    r = np.sqrt(x * x + y * y)
    disc = 1.0 - smoothstep(0.82, 0.98, r)
    rim = smoothstep(0.45, 0.85, r) * disc
    highlight = np.exp(-((x + 0.32) ** 2 + (y + 0.34) ** 2) / 0.012)
    alpha = np.clip(0.18 * disc + 0.55 * rim + 0.9 * highlight, 0.0, 1.0)
    value = np.clip(0.82 + 0.18 * highlight, 0.0, 1.0)
    save("water_bead.png", alpha, value)


def fine_spray() -> None:
    x, y = grid(64, 64)
    r2 = x * x + y * y
    alpha = np.exp(-r2 / 0.18) * (1.0 - smoothstep(0.85, 1.0, np.sqrt(r2)))
    save("fine_spray.png", alpha)


def roof_stream() -> None:
    x, y = grid(64, 64)
    across = np.exp(-(x * x) / 0.02)
    along = smoothstep(-1.0, -0.55, y) * (1.0 - smoothstep(0.45, 1.0, y))
    core = np.exp(-(x * x) / 0.004)
    alpha = across * along * 0.75 + core * along * 0.25
    save("roof_stream.png", alpha)


def rain_streak() -> None:
    x, y = grid(16, 256)
    across = np.exp(-(x * x) / 0.12)
    along = smoothstep(-1.0, -0.7, y) * (1.0 - smoothstep(0.6, 1.0, y))
    alpha = across * along
    save("rain_streak.png", alpha)


def exhaust_puff() -> None:
    rng = np.random.default_rng(SEED)
    size = 128
    noise = np.zeros((size, size))
    for octave, weight in ((4, 0.5), (8, 0.3), (16, 0.2)):
        coarse = rng.random((octave + 1, octave + 1))
        image = Image.fromarray(np.round(coarse * 255).astype(np.uint8), "L")
        noise += weight * np.asarray(
            image.resize((size, size), Image.Resampling.BICUBIC), dtype=float) / 255.0
    x, y = grid(size, size)
    r = np.sqrt(x * x + y * y)
    falloff = 1.0 - smoothstep(0.25, 1.0, r)
    alpha = falloff * np.clip(0.35 + 0.9 * (noise - 0.5) + 0.4, 0.0, 1.0)
    save("exhaust_puff.png", alpha)


def main() -> None:
    water_bead()
    fine_spray()
    roof_stream()
    rain_streak()
    exhaust_puff()


if __name__ == "__main__":
    main()
